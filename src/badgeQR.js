const cache = {};

// { n, runs, path } for a URL, or null: `runs` are the dark modules as
// horizontal runs [x, y, length] (one rect per run, so a row of dark modules
// is one shape with no seams inside it), `path` the same as an SVG path in
// module units (the motion badges' <svg>)
export function qrFor(url) {
  if (!ROWS[url]) return null;
  if (cache[url]) return cache[url];
  const rows = ROWS[url];
  const runs = rows.flatMap((row, y) => {
    const out = [];
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== '1') continue;
      let n = 1;
      while (row[x + n] === '1') n++;
      out.push([x, y, n]);
      x += n - 1;
    }
    return out;
  });
  const path = runs.map(([x, y, n]) => `M${x} ${y}h${n}v1h-${n}z`).join('');
  return (cache[url] = { n: rows.length, runs, path });
}
